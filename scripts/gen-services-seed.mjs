// Generates supabase/migrations/0003_seed_services.sql from services.json.
// Run: node scripts/gen-services-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const data = JSON.parse(readFileSync('services.json', 'utf8'))
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const paise = (r) => (r == null ? 'null' : String(r * 100))
const inr = (n) => '₹' + new Intl.NumberFormat('en-IN').format(n)

// ---- normalise every item to { category, name, gender, std, prime, unit, hint }
const items = []
const parseNote = (note) => {
  const per = note.match(/^(\d+)\s+per\s+(\w+)/i)
  if (per) return { std: +per[1], unit: per[2].toLowerCase(), hint: null }
  const on = note.match(/^(\d+)\s+onwards/i)
  if (on) return { std: null, unit: null, hint: `${inr(+on[1])} onwards` }
  return { std: null, unit: null, hint: note }
}
const parseRange = (r) => {
  const m = r.match(/^(\d+)-(\d+|above)$/)
  if (!m) return r
  return m[2] === 'above' ? `${inr(+m[1])} and above` : `${inr(+m[1])}–${new Intl.NumberFormat('en-IN').format(+m[2])}`
}
for (const [key, gender] of [['menServices', 'men'], ['womenServices', 'women']]) {
  for (const cat of data[key].categories) {
    for (const it of cat.items) {
      let std = it.nonMemberPrice ?? null, unit = null, hint = null
      if (it.nonMemberPriceNote) ({ std, unit, hint } = parseNote(it.nonMemberPriceNote))
      if (it.nonMemberPriceRange) hint = parseRange(it.nonMemberPriceRange)
      items.push({ category: cat.name, name: it.service.trim(), gender, std, prime: it.memberPrice ?? null, unit, hint })
    }
  }
}

// ---- de-duplicate: identical name + prices across men and women become one 'both' row
// (women's brand-specific "Facials - X" categories keep their own rows for context)
const keyOf = (i) => `${i.name.toLowerCase()}|${i.std}|${i.prime}|${i.unit}|${i.hint}`
const merged = []
const seen = new Map()
const merges = []
for (const it of items) {
  const brandFacial = it.gender === 'women' && it.category.startsWith('Facials -')
  const k = keyOf(it)
  const prev = seen.get(k)
  if (!brandFacial && prev && prev.gender !== it.gender && prev.gender !== 'both') {
    prev.gender = 'both'
    merges.push(`${prev.name} (${prev.category} + ${it.category})`)
  } else {
    const row = { ...it }
    merged.push(row)
    if (!brandFacial) seen.set(k, row)
  }
}

// ---- categories (first appearance order)
const cats = new Map()
for (const it of merged) {
  const k = it.category + '|' + it.gender
  if (!cats.has(k)) cats.set(k, { name: it.category, gender: it.gender, sort: cats.size })
}
// a category used by both genders but first created as 'men' keeps its own gender tag; fine for display grouping

let sql = '-- Generated by scripts/gen-services-seed.mjs from services.json. Do not edit by hand.\n'
sql += 'insert into public.service_categories(name, gender, sort) values\n'
sql += [...cats.values()].map((c) => `  (${q(c.name)}, ${q(c.gender)}, ${c.sort})`).join(',\n') + ';\n\n'
sql += 'insert into public.services(category_id, name, gender, standard_price, prime_price, unit_label, price_hint, sort)\nselect c.id, v.name, v.gender, v.std, v.prime, v.unit, v.hint, v.sort\nfrom (values\n'
sql += merged.map((it, n) =>
  `  (${q(it.category)}, ${q(it.name)}, ${q(it.gender)}, ${paise(it.std)}::bigint, ${paise(it.prime)}::bigint, ${it.unit ? q(it.unit) : 'null::text'}, ${it.hint ? q(it.hint) : 'null::text'}, ${n})`
).join(',\n')
sql += '\n) as v(cat, name, gender, std, prime, unit, hint, sort)\njoin public.service_categories c on c.name = v.cat and c.gender = v.gender;\n\n'

// ---- packages (bundles with one offer price)
sql += `insert into public.service_categories(name, gender, sort) values ('Pre-Bridal / Grooming Packages', 'both', ${cats.size});\n\n`
const pkgs = []
for (const [key, gender, label] of [['women', 'women', 'Women'], ['men', 'men', 'Men']]) {
  for (const p of data.preBridalPackages[key]) {
    pkgs.push({ name: `${p.name} (${label})`, gender, price: p.offerPrice ?? p.specialOffer, items: p.items })
  }
}
sql += 'insert into public.services(category_id, name, gender, standard_price, is_package, sort)\nselect c.id, v.name, v.gender, v.price, true, v.sort\nfrom (values\n'
sql += pkgs.map((p, n) => `  (${q(p.name)}, ${q(p.gender)}, ${p.price * 100}::bigint, ${1000 + n})`).join(',\n')
sql += "\n) as v(name, gender, price, sort)\njoin public.service_categories c on c.name = 'Pre-Bridal / Grooming Packages';\n\n"
sql += 'insert into public.package_items(package_id, label, sort)\nselect s.id, v.label, v.sort\nfrom (values\n'
sql += pkgs.flatMap((p) => p.items.map((label, n) => `  (${q(p.name)}, ${q(label)}, ${n})`)).join(',\n')
sql += '\n) as v(pkg, label, sort)\njoin public.services s on s.name = v.pkg and s.is_package;\n'

writeFileSync('supabase/migrations/0003_seed_services.sql', sql)
console.log(`items: ${items.length} → ${merged.length} after merge; packages: ${pkgs.length}`)
console.log('merged:', merges.join('; '))
